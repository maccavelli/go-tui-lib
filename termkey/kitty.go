func init() {
	kittyKeys[0x00] = KeyEvent{Code: KeySpace, Mod: ModCtrl}
	for i := 0x01; i <= 0x1a; i++ {
		if _, ok := kittyKeys[i]; !ok {
			kittyKeys[i] = KeyEvent{Code: rune(i + 0x60), Mod: ModCtrl}
		}
	}
	for i := 0x1c; i <= 0x1f; i++ {
		if _, ok := kittyKeys[i]; !ok {
			kittyKeys[i] = KeyEvent{Code: rune(i + 0x40), Mod: ModCtrl}
		}
	}
}
